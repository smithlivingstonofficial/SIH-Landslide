export function getHighRiskDistricts() {
  return NER_DISTRICTS.filter(d => d.riskLevel === "VERY_HIGH" || d.riskLevel === "HIGH");
}

export function getDistrictById(id) {
  return NER_DISTRICTS.find(d => d.id === id);
}

export function getRiskColor(riskLevel) {
  return RISK_LEVELS[riskLevel]?.color || "#6b7280";
}

export function getAlertsBySeverity(severity) {
  if (severity === "All") return RECENT_ALERTS;
  return RECENT_ALERTS.filter(a => a.severity === severity);
}

export function getStateStats(stateCode) {
  const districts = getDistrictsByState(stateCode);
  return {
    totalDistricts: districts.length,
    highRisk: districts.filter(d => d.riskLevel === "VERY_HIGH" || d.riskLevel === "HIGH").length,
    mediumRisk: districts.filter(d => d.riskLevel === "MEDIUM").length,
    lowRisk: districts.filter(d => d.riskLevel === "LOW" || d.riskLevel === "VERY_LOW").length,
    topHighRisk: districts
      .sort((a, b) => b.riskScore - a.riskScore)
      .slice(0, 5),
  };
}

